      const scaleMetres = groundWidth >= 220 ? 50 : 20;
      const scaleWidth = width * scaleMetres / groundWidth;
      ctx.save();
      const margin = large ? 18 : 14;
      const fontSize = large ? 20 : window.innerWidth <= 700 ? 26 : 20;
