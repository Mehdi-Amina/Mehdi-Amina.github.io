    function heatColor(value) {
      const scaled = Math.min(0.999999, Math.max(0, value)) * 4;
      const index = Math.floor(scaled);
      const mix = scaled - index;
      return palette[index].map((channel, n) => Math.round(channel * (1 - mix) + palette[index + 1][n] * mix));
    }

    function selectRegions(field, threshold) {
      const { values, width, height } = field;
      const visited = new Uint8Array(values.length);
      const selected = new Uint8Array(values.length);
      const labels = new Uint16Array(values.length);
      const regions = [];
      for (let start = 0; start < values.length; start++) {
        if (visited[start] || values[start] < threshold) continue;
        const queue = [start];
        visited[start] = 1;
        let size = 0;
        for (let cursor = 0; cursor < queue.length; cursor++) {
          const i = queue[cursor];
          const x = i % width;
          const y = Math.floor(i / width);
          size++;
          for (const next of [x > 0 ? i - 1 : -1, x < width - 1 ? i + 1 : -1, y > 0 ? i - width : -1, y < height - 1 ? i + width : -1]) {
            if (next >= 0 && !visited[next] && values[next] >= threshold) {
              visited[next] = 1;
              queue.push(next);
            }
          }
        }
        if (size >= 12) {
          const id = regions.length + 1;
          let sumX = 0;
          let sumY = 0;
          let peakIndex = queue[0];
          queue.forEach(index => {
            selected[index] = 1;
            labels[index] = id;
            sumX += index % width + 0.5;
            sumY += Math.floor(index / width) + 0.5;
            if (values[index] > values[peakIndex]) peakIndex = index;
          });
          regions.push({ id, count: size, centroidX: sumX / size, centroidY: sumY / size, peakIndex, peakIntensity: values[peakIndex], cells: queue });
        }
      }
      return { selected, labels, regions, count: regions.length };
    }

    function selectionFor(place, threshold) {
      const key = threshold.toFixed(2);
      if (!place.selections.has(key)) {
        const selection = selectRegions(place.heat, threshold);
        const { width, height } = place.heat;
        const bounds = projectedBounds(place);
        const dx = (bounds.east - bounds.west) / width;
        const rowAreas = Array.from({ length: height }, (_, y) => {
          const north = pointAt(place, 0, y / height).lat * Math.PI / 180;
          const south = pointAt(place, 0, (y + 1) / height).lat * Math.PI / 180;
          return dx * earthRadius * (Math.sin(north) - Math.sin(south));
        });
        selection.regions.forEach(region => {
          region.centroid = pointAt(place, region.centroidX / width, region.centroidY / height);
          region.peak = pointAt(place, (region.peakIndex % width + 0.5) / width, (Math.floor(region.peakIndex / width) + 0.5) / height);
          region.area = region.cells.reduce((sum, index) => sum + rowAreas[Math.floor(index / width)], 0);
          delete region.cells;
        });
        place.selections.set(key, selection);
        if (place.selections.size > 8) place.selections.delete(place.selections.keys().next().value);
      }
      return place.selections.get(key);
    }

    function projectedBounds(place) {
      const [west, south, east, north] = place.bounds;
      const projectY = latitude => earthRadius * Math.log(Math.tan(Math.PI / 4 + latitude * Math.PI / 360));
      return { west: earthRadius * west * Math.PI / 180, east: earthRadius * east * Math.PI / 180, south: projectY(south), north: projectY(north) };
    }

    //keep the coordinate transform tied to the original aerial image bounds
    function pointAt(place, xFraction, yFraction) {
      const bounds = projectedBounds(place);
      const x = bounds.west + xFraction * (bounds.east - bounds.west);
      const y = bounds.north - yFraction * (bounds.north - bounds.south);
      return { lat: (2 * Math.atan(Math.exp(y / earthRadius)) - Math.PI / 2) * 180 / Math.PI, lon: x / earthRadius * 180 / Math.PI };
    }

    function coordinateText(point) {
      return `${point.lat.toFixed(6)}° N · ${point.lon.toFixed(6)}° E`;
    }

    function selectedRegion(place, selection) {
      if (!selectedAnchor || selectedAnchor.placeId !== place.id) return null;
      const id = selection.labels[selectedAnchor.cell];
      return id ? selection.regions[id - 1] : null;
    }

