    function loadImage(file, name) {
      return new Promise((resolve, reject) => {
        const image = new Image();
        image.onload = () => resolve(image);
        image.onerror = () => reject(new Error(`The image for ${name} could not be loaded`));
        image.src = file;
      });
    }

    //read the saved simulation texture without loading any measured dataset
    function decodeSimulatedHeat(texture) {
      const canvas = document.createElement('canvas');
      canvas.width = texture.naturalWidth;
      canvas.height = texture.naturalHeight;
      if (canvas.width !== 240 || canvas.height !== 160) throw new Error('A simulation texture has unexpected dimensions');
      const context = canvas.getContext('2d', { willReadFrequently: true });
      context.drawImage(texture, 0, 0);
      const pixels = context.getImageData(0, 0, canvas.width, canvas.height).data;
      const values = new Float32Array(canvas.width * canvas.height);
      for (let i = 0; i < values.length; i++) {
        values[i] = pixels[i * 4 + 3] === 0 ? -1 : (pixels[i * 4] * 256 + pixels[i * 4 + 1]) / 10000;
      }
      return { width: canvas.width, height: canvas.height, values };
    }

    async function initialize() {
      try {
        places = await Promise.all(publicScenes.map(async place => {
          const [image, texture] = await Promise.all([loadImage(place.file, place.name), loadImage(place.heatTexture, place.name)]);
          const heat = decodeSimulatedHeat(texture);
          return { ...place, image, heat, selections: new Map() };
        }));
        gallery.replaceChildren(...places.map(createArea));
        gallery.setAttribute('aria-busy', 'false');
        const nav = document.getElementById('area-nav');
        const firstByArea = [...new Map(places.map(place => [place.area, places.find(item => item.area === place.area)])).values()];
        firstByArea.forEach(place => {
          const link = element('a', '', place.name.replace(/ fields$/i, ''));
          link.href = `#${place.id}`;
          nav.append(link);
        });
        const sections = firstByArea.map(place => document.getElementById(place.id));
        const weatherSection = document.getElementById('weather-analysis');
        if (weatherSection) sections.push(weatherSection);
        const links = [...nav.querySelectorAll('a')];
        const setCurrent = hash => links.forEach(link => link.setAttribute('aria-current', link.hash === hash ? 'location' : 'false'));
        links.forEach(link => link.addEventListener('click', () => setCurrent(link.hash)));
        const observer = new IntersectionObserver(entries => {
          const current = entries.filter(entry => entry.isIntersecting).sort((a, b) => a.boundingClientRect.top - b.boundingClientRect.top)[0];
          if (!current) return;
          setCurrent(`#${current.target.id}`);
        }, { rootMargin: '-100px 0px -45% 0px' });
        sections.forEach(section => observer.observe(section));
      } catch (error) {
        gallery.setAttribute('aria-busy', 'false');
        const box = element('div', 'error');
        box.setAttribute('role', 'alert');
        box.append(element('h2', '', 'The preview could not load'), element('p', '', error.message), element('p', '', 'Reload the page to try the image files again.'));
        gallery.replaceChildren(box);
      }
    }
    initialize();
